    <p class="box"><strong>English summary.</strong> This CMS is used by the staff of our pesantren and Ma'had Aly to publish to the institution's own Facebook Pages, Instagram and TikTok accounts. When an authorized staff member connects an account, we store the account name, ID, profile picture and the access token the platform issues. Tokens are encrypted and used only to publish posts the staff schedule. We do not read followers, messages or analytics, do not sell or share data, and delete it when the account is disconnected or when you request deletion.</p>

    <h2>1. Data yang kami kumpulkan</h2>
    <p>Saat staf yang berwenang menghubungkan akun media sosial lembaga (Halaman Facebook, akun Instagram Bisnis, atau akun TikTok), sistem menyimpan:</p>
    <ul>
        <li>nama akun, ID akun, nama pengguna, dan foto profil;</li>
        <li>token akses dari platform (disimpan terenkripsi) beserta waktu kedaluwarsanya;</li>
        <li>izin (scope) yang diberikan, yaitu hanya untuk menampilkan daftar halaman dan menerbitkan konten.</li>
    </ul>
    <p>Kami tidak mengakses pesan, daftar pengikut, data pribadi pengikut, maupun statistik akun.</p>

    <h2>2. Penggunaan data</h2>
    <p>Data hanya digunakan untuk menerbitkan atau menjadwalkan unggahan yang dibuat staf lembaga ke akun milik lembaga sendiri, serta menampilkan status penerbitan. Setiap tindakan tercatat di log audit sistem.</p>

    <h2>3. Penyimpanan dan keamanan</h2>
    <p>Token disimpan terenkripsi di server lembaga dan tidak pernah ditampilkan atau dikirim ke pihak lain. Hanya pengguna dengan peran Social Media Manager atau Superadmin yang dapat menghubungkan akun dan menerbitkan konten.</p>

    <h2>4. Berbagi data</h2>
    <p>Kami tidak menjual, menyewakan, atau membagikan data kepada pihak ketiga. Data hanya dikirim ke platform terkait (Meta atau TikTok) untuk menerbitkan konten.</p>

    <h2>5. Penghapusan data</h2>
    <ul>
        <li>Memutuskan akun di menu <em>Social accounts</em> menghapus token dan data akun dari sistem.</li>
        <li>Anda juga dapat mencabut akses aplikasi di pengaturan Facebook (Pengaturan → Aplikasi dan Situs Web) atau TikTok (Pengaturan → Keamanan → Aplikasi yang diizinkan). Facebook akan mengirimkan permintaan penghapusan ke sistem kami secara otomatis, dan Anda menerima kode konfirmasi untuk memeriksa statusnya.</li>
        <li>Permintaan penghapusan juga dapat dikirim melalui email kontak di bawah. Kami memprosesnya paling lama 30 hari.</li>
    </ul>

    <h2>6. Perubahan kebijakan</h2>
    <p>Perubahan kebijakan ini diumumkan di halaman ini beserta tanggal pembaruannya.</p>
